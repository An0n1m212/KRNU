// 1. Функція вітання
console.log("Завдання 1:");

function greet(firstName, lastName) {
    console.log("Привіт, " + firstName + " " + lastName + "!");
}

greet("Богдан", "Рафієв");

// 2. Об'єкт, що представляє людину
console.log("Завдання 2:");

var person = {
    name: "Богдан",
    age: 20,
    email: "bohdan.rafiev@example.com"
};

console.log("Ім'я:", person.name);

// Додаємо нову властивість після створення об'єкта
person.city = "Кременчук";
console.log("Місто:", person.city);

// 3. Масив чисел і цикл for
console.log("Завдання 3:");

var numbers = [3, 8, 15, 22, 7];

for (var i = 0; i < numbers.length; i++) {
    console.log(numbers[i]);
}

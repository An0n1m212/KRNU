// ---------- Завдання 2. Оператор вибору switch ----------
// Створити змінну "dayOfWeek" і вивести повідомлення для кожного
// дня тижня, використавши гілку default.

console.log("");
console.log("Завдання 2:");

var dayOfWeek = "понеділок";

switch (dayOfWeek) {
    case "понеділок":
        console.log("Це перший день тижня");
        break;
    case "вівторок":
        console.log("Це другий день тижня");
        break;
    case "середа":
        console.log("Це середина тижня");
        break;
    case "четвер":
        console.log("Це четвертий день тижня");
        break;
    case "п'ятниця":
        console.log("Це останній робочий день тижня");
        break;
    case "субота":
        console.log("Це перший вихідний день");
        break;
    case "неділя":
        console.log("Це останній день тижня");
        break;
    default:
        console.log("Такого дня тижня не існує");
}

